-- 22)  Rank products by their total revenue using RANK()

select
	product_id,
    product_name,
    sum(quantity * price) as total_revenue,
    Rank() over (order by sum(quantity  * price) desc) as revenue_rank
    from sales
    group by product_id, product_name
    order by revenue_rank limit 5;
 
 -- 23) Rank products within each product category using PARTITION BY
 
 select
	product_category,
    product_Id,
    product_name,
    sum(quantity * price) as total_revenue,
    Rank() over ( partition by product_category 
				order by sum(quantity * price) desc) as category_rank
                from sales
                group by product_category, product_id , product_name
                order by product_category, category_rank;
                
